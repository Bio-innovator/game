function makeFloor([dark, light]) {
  return Array.from({ length: 24 }, (_, y) => Array.from({ length: 24 }, (_, x) => {
    if (x === 0 || y === 0 || x === 23 || y === 23) return dark;
    if (x % 8 === 0 || y % 8 === 0) return dark;
    if ((x * 3 + y * 5) % 13 === 0) return dark;
    return light;
  }).join(""));
}

